"""WGS84 参考椭球的物理常量。

常量以全局变量形式直接给出，便于查阅。
"""

WGS84_A = 6378137.0           # 长半轴 (m)
WGS84_F = 1.0 / 298.257222101  # 扁率
WGS84_B = 6356752.3141        # 短半轴 (m)
WGS84_GM = 3.98600569e14      # 地心引力常数 (m^3/s^2)
WGS84_OMEGA = 7.292115e-5     # 地球自转角速度 (rad/s)


def first_eccentricity():
    """WGS84 参考椭球的第一偏心率 e。

    公式：e^2 = 2*f - f^2
    """
    f = WGS84_F
    return (2 * f - f * f) ** 0.5
